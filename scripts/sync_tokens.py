#!/usr/bin/env python3
"""
Regenerate the colour block in app/globals.css from lib/tokens.ts.

Run after adding or renaming a token:   python scripts/sync_tokens.py
(Changing a token's value needs nothing: values are read from tokens.ts at build time.)
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOKENS = ROOT / "lib" / "tokens.ts"
CSS = ROOT / "app" / "globals.css"
START, END = "/* tokens:start (generated by scripts/sync_tokens.py) */", "/* tokens:end */"


def main() -> int:
    src = TOKENS.read_text(encoding="utf-8")
    block = src[src.index("export const light = {"): src.index("} as const;")]
    names = re.findall(r"^\s*'?([a-z0-9-]+)'?\s*:\s*'#[0-9a-fA-F]{3,8}'", block, re.M)
    if not names:
        print("ERROR: no tokens found in lib/tokens.ts", file=sys.stderr)
        return 1

    lines = "\n".join(f"  --color-{n}: var(--tok-{n});" for n in names)
    css = CSS.read_text(encoding="utf-8")
    if START not in css or END not in css:
        print(f"ERROR: markers not found in {CSS.relative_to(ROOT)}", file=sys.stderr)
        return 1
    before, rest = css.split(START, 1)
    _, after = rest.split(END, 1)
    CSS.write_text(f"{before}{START}\n{lines}\n  {END}{after}", encoding="utf-8")
    print(f"Synced {len(names)} colour tokens into {CSS.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
